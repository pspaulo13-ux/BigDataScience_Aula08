numeros = [5,7,4,1,2,8,13,6]
total = sum(numeros) # Soma todos os elementos da lista
quantidade = len(numeros) # Retorna a quantidade de elementos da lista
ordenados = sorted(numeros) # Ordena os elementos da lista do menor para o maior

print(f'Total: {total}')
print(f'Quantidade: {quantidade}') 
print(f'Ordenados: {ordenados}')
